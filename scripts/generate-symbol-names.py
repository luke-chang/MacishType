#!/usr/bin/env python3
"""Build the Traditional Chinese symbol-name table from CLDR annotations.

Interface (external-resources processor convention):
    generate-symbol-names.py <cldr-annotations.json> <output> <source-url>

Keeps single-codepoint BMP symbols and their `tts` name, sorted by
codepoint. The hand-curated override table (SymbolNamesOverride.zh-Hant.txt
beside this script) is overlaid on the CLDR base; the override wins on
conflicts. The .inputs sidecar folds the override into the stamp, so
editing it regenerates this table.
"""

import json
import os
import sys


def main():
    input_path, output_path, source_url = sys.argv[1:4]
    with open(input_path, encoding="utf-8") as source:
        annotations = json.load(source)["annotations"]["annotations"]

    names = {}
    for symbol, value in annotations.items():
        codepoints = [ord(character) for character in symbol]
        if len(codepoints) != 1 or codepoints[0] > 0xFFFF:
            continue
        tts = value.get("tts")
        if tts:
            names[symbol] = tts[0]

    overlaid = 0
    override_path = os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "SymbolNamesOverride.zh-Hant.txt")
    with open(override_path, encoding="utf-8") as override:
        for line in override:
            line = line.rstrip("\n")
            if not line or line.startswith("#") or "\t" not in line:
                continue
            symbol, name = line.split("\t", 1)
            names[symbol] = name
            overlaid += 1

    header = [
        "# Symbol-to-name table (CLDR zh-Hant annotations, single BMP "
        "symbols).",
        "# format: symbol<TAB>name",
        f"# source: {source_url}",
        "# generated by scripts/generate-symbol-names.py via "
        "external-resources - DO NOT EDIT",
        "",
    ]
    lines = [f"{symbol}\t{names[symbol]}"
             for symbol in sorted(names, key=lambda s: (ord(s[0]), s))]
    with open(output_path, "w", encoding="utf-8") as output:
        output.write("\n".join(header + lines) + "\n")
    print(f"wrote {len(lines)} entries, {overlaid} overridden",
          file=sys.stderr)


if __name__ == "__main__":
    main()
