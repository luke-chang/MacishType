#!/usr/bin/env python3
"""Derive an associated-mode lookup table from a phrase-frequency corpus.

Interface (external-resources processor convention):
    generate-associated-dictionary.py <input> <output> <source-url>

Reads <input> (`phrase<whitespace>freq` per line, the phrase.occ format),
keeps CJK phrases of at least two characters, groups them by leading
character, deduplicates the followers by their own leading character
(keeping the highest-frequency variant), and writes the top 60 followers
per prefix. Mirrors MacishType's Scripts/GenerateAssociatedDictionary.swift
so both platforms produce identical tables from the same pinned source.
"""

import sys
import unicodedata

MAX_ENTRIES_PER_PREFIX = 60


def is_all_cjk(phrase):
    # Matches the Swift generator's `.otherLetter` gate (Unicode Lo), which
    # covers CJK ideographs while excluding punctuation, digits, and Latin.
    return bool(phrase) and all(
        unicodedata.category(ch) == "Lo" for ch in phrase)


def main():
    input_path, output_path, source_url = sys.argv[1:4]

    prefix_map = {}
    with open(input_path, encoding="utf-8") as source:
        for line in source:
            parts = line.split()
            if len(parts) != 2:
                continue
            phrase, count = parts[0], parts[1]
            try:
                freq = int(count)
            except ValueError:
                continue
            if len(phrase) < 2 or not is_all_cjk(phrase):
                continue
            prefix_map.setdefault(phrase[0], []).append((phrase[1:], freq))

    header = [
        "# Associated-phrase lookup table (leading character -> following "
        "phrases).",
        "# format: leadingChar<TAB>phrase[<space>phrase...]",
        f"# source: {source_url}",
        "# generated by scripts/generate-associated-dictionary.py via "
        "external-resources - DO NOT EDIT",
        "",
    ]
    lines = []
    for prefix in sorted(prefix_map):
        ranked = sorted(prefix_map[prefix], key=lambda entry: -entry[1])
        seen_leading = set()
        picked = []
        for remainder, _freq in ranked:
            leading = remainder[0]
            if leading in seen_leading:
                continue
            seen_leading.add(leading)
            picked.append(remainder)
            if len(picked) >= MAX_ENTRIES_PER_PREFIX:
                break
        if picked:
            lines.append(f"{prefix}\t{' '.join(picked)}")

    with open(output_path, "w", encoding="utf-8") as output:
        output.write("\n".join(header + lines) + "\n")
    print(f"wrote {len(lines)} prefixes", file=sys.stderr)


if __name__ == "__main__":
    main()
