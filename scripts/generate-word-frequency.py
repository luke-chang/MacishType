#!/usr/bin/env python3
"""Extract the single-character subset of a phrase-occurrence corpus into a
per-character frequency table.

Interface (external-resources processor convention):
    generate-word-frequency.py <input> <output> <source-url>

Reads <input> (`entry<space>count` per line, the phrase.occ format), keeps
only entries whose key is exactly one Unicode scalar, and writes them to
<output> in the input's native order. Mirrors MacishType's
Scripts/GenerateWordFrequency.swift so both platforms produce identical
tables from the same pinned source.
"""

import sys


def main():
    input_path, output_path, source_url = sys.argv[1:4]
    entries = []
    with open(input_path, encoding="utf-8") as source:
        for line in source:
            parts = line.split(None, 1)
            if len(parts) != 2:
                continue
            key, count = parts[0], parts[1].strip()
            if len(key) == 1:
                entries.append(f"{key}\t{count}")

    header = [
        "# Per-character frequency table (single-character subset of the "
        "source corpus).",
        "# format: char<TAB>count",
        f"# source: {source_url}",
        "# generated by scripts/generate-word-frequency.py via "
        "external-resources - DO NOT EDIT",
        "",
    ]
    with open(output_path, "w", encoding="utf-8", newline="\n") as output:
        output.write("\n".join(header + entries) + "\n")
    print(f"wrote {len(entries)} entries", file=sys.stderr)


if __name__ == "__main__":
    main()
